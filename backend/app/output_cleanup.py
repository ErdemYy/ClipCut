"""Guarded cleanup of generated publish output folders and old main renders.

Publishing jobs create ``outputs/<32-hex>/`` folders. They are never overwritten,
so incremental work accumulates disk usage. This module offers only folders and
old main renders that are old and unreferenced, moves them into a per-project
seven-day trash instead of deleting them immediately, and can restore or purge
them explicitly. Source media, covers, the current main render, previews and
project edits are never deleted.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import stat
import time
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable

from pydantic import BaseModel, Field, field_validator

TOKEN_RE = re.compile(r"^[a-f0-9]{32}$")
# Only files generated by ``task_render`` (``outputs/clipcut_<stamp>[_<hex>].mp4``).
RENDER_NAME_RE = re.compile(r"^clipcut_[A-Za-z0-9_]{1,100}\.mp4$")
MIN_AGE_SECONDS = 60 * 60
TRASH_RETENTION_SECONDS = 7 * 24 * 60 * 60
MAX_TOKENS = 50
MAX_RENDER_FILES = 50
MAX_TRASH_BATCH = 50
CATEGORY_IDS = ("source", "renders", "staging", "previews", "work", "trash", "other")
PREVIEW_DIRS = ("previews", "clip_previews")
TRASH_DIR = ".trash"

_REFERENCE_RE = re.compile(r"/media/projects/([A-Za-z0-9_-]+)/outputs/([a-f0-9]{32})/")
_RELATIVE_REFERENCE_RE = re.compile(r"(?:^|[\\/])outputs[\\/]([a-f0-9]{32})(?:[\\/]|$)")
_RENDER_REFERENCE_RE = re.compile(
    r"/media/projects/([A-Za-z0-9_-]+)/outputs/(clipcut_[A-Za-z0-9_]{1,100}\.mp4)")
_RELATIVE_RENDER_REFERENCE_RE = re.compile(
    r"(?:^|[\\/])outputs[\\/](clipcut_[A-Za-z0-9_]{1,100}\.mp4)")


class OutputCleanupBody(BaseModel):
    tokens: list[str] = Field(..., min_length=1, max_length=MAX_TOKENS)

    @field_validator("tokens")
    @classmethod
    def _unique_tokens(cls, values: list[str]) -> list[str]:
        if len(set(values)) != len(values):
            raise ValueError("Her çıktı klasörü bir kez gönderilmeli.")
        if any(not TOKEN_RE.fullmatch(token) for token in values):
            raise ValueError("Geçersiz çıktı klasörü.")
        return values


class RenderCleanupBody(BaseModel):
    files: list[str] = Field(..., min_length=1, max_length=MAX_RENDER_FILES)

    @field_validator("files")
    @classmethod
    def _unique_files(cls, values: list[str]) -> list[str]:
        if len(set(values)) != len(values):
            raise ValueError("Her ana render bir kez gönderilmeli.")
        if any(not RENDER_NAME_RE.fullmatch(name) for name in values):
            raise ValueError("Geçersiz ana render dosyası.")
        return values


class TrashRestoreBody(BaseModel):
    ids: list[str] = Field(..., min_length=1, max_length=MAX_TRASH_BATCH)

    @field_validator("ids")
    @classmethod
    def _unique_ids(cls, values: list[str]) -> list[str]:
        if len(set(values)) != len(values):
            raise ValueError("Her çöp öğesi bir kez gönderilmeli.")
        if any(not TOKEN_RE.fullmatch(value) for value in values):
            raise ValueError("Geçersiz çöp öğesi.")
        return values


class TrashEmptyBody(BaseModel):
    ids: list[str] = Field(default_factory=list, max_length=MAX_TRASH_BATCH)

    @field_validator("ids")
    @classmethod
    def _unique_ids(cls, values: list[str]) -> list[str]:
        if len(set(values)) != len(values):
            raise ValueError("Her çöp öğesi bir kez gönderilmeli.")
        if any(not TOKEN_RE.fullmatch(value) for value in values):
            raise ValueError("Geçersiz çöp öğesi.")
        return values


def referenced_tokens(project_id: str, values: Iterable[Any]) -> set[str]:
    """Collect output tokens referenced by stored results or project paths."""
    tokens: set[str] = set()
    for value in values:
        tokens.update(_tokens_in(project_id, value))
    return tokens


def _tokens_in(project_id: str, value: Any) -> set[str]:
    if isinstance(value, str):
        absolute = list(_REFERENCE_RE.finditer(value))
        if absolute:
            return {match.group(2) for match in absolute if match.group(1) == project_id}
        return set(_RELATIVE_REFERENCE_RE.findall(value))
    if isinstance(value, dict):
        return set().union(*(_tokens_in(project_id, item) for item in value.values())) if value else set()
    if isinstance(value, (list, tuple, set)):
        return set().union(*(_tokens_in(project_id, item) for item in value)) if value else set()
    return set()


def render_references(project_id: str, values: Iterable[Any]) -> set[str]:
    """Collect ``outputs/clipcut_*.mp4`` paths referenced by project/result data."""
    references: set[str] = set()
    for value in values:
        references.update(_renders_in(project_id, value))
    return references


def _renders_in(project_id: str, value: Any) -> set[str]:
    if isinstance(value, str):
        absolute = list(_RENDER_REFERENCE_RE.finditer(value))
        if absolute:
            return {f"outputs/{match.group(2)}" for match in absolute if match.group(1) == project_id}
        return {f"outputs/{name}" for name in _RELATIVE_RENDER_REFERENCE_RE.findall(value)}
    if isinstance(value, dict):
        return set().union(*(_renders_in(project_id, item) for item in value.values())) if value else set()
    if isinstance(value, (list, tuple, set)):
        return set().union(*(_renders_in(project_id, item) for item in value)) if value else set()
    return set()


def _is_link(path: Path) -> bool:
    """Reject symlinks and Windows junctions without following them."""
    try:
        if path.is_symlink():
            return True
        if os.name == "nt":
            attributes = path.stat(follow_symlinks=False).st_file_attributes
            return bool(attributes & stat.FILE_ATTRIBUTE_REPARSE_POINT)
    except FileNotFoundError:
        return False
    except OSError:
        return True
    return False


def _entry_is_link(entry: os.DirEntry[str] | Path) -> bool:
    """Same protection as :func:`_is_link`, without an extra path round-trip."""
    try:
        if entry.is_symlink():
            return True
        if os.name == "nt":
            attributes = entry.stat(follow_symlinks=False).st_file_attributes
            return bool(attributes & stat.FILE_ATTRIBUTE_REPARSE_POINT)
    except FileNotFoundError:
        return False
    except OSError:
        return True
    return False


def _measure(directory: Path) -> tuple[int, int, str | None]:
    """Return (bytes, files, unsafe reason). Never follows links or nested dirs."""
    size = files = 0
    try:
        for item in directory.rglob("*"):
            if _is_link(item):
                return size, files, "symlink"
            if item.is_dir():
                return size, files, "nested"
            if not item.is_file():
                return size, files, "special"
            size += item.stat().st_size
            files += 1
    except OSError:
        return size, files, "unreadable"
    return size, files, None


def _relative(value: str | None) -> str:
    """Normalize a project-relative path for category classification."""
    if not value:
        return ""
    path = value.replace("\\", "/")
    while path.startswith("./"):
        path = path[2:]
    return path.lstrip("/")


def _category_for(relative: str, source_files: set[str]) -> str:
    if relative in source_files:
        return "source"
    parts = relative.split("/")
    if parts[0] == TRASH_DIR:
        # Manifest metadata is project bookkeeping; the trash row shows payload bytes.
        if len(parts) >= 3 and parts[2] in ("manifest.json", "manifest.json.tmp"):
            return "other"
        return "trash"
    if parts[0] == "work":
        return "work"
    if parts[0] == "outputs" and len(parts) >= 2:
        if parts[1] in PREVIEW_DIRS:
            return "previews"
        if len(parts) >= 3 and TOKEN_RE.fullmatch(parts[1]):
            return "staging"
        if len(parts) == 2 and RENDER_NAME_RE.fullmatch(parts[1]):
            return "renders"
    return "other"


def _walk_project(root: Path):
    """Yield ``(relative posix path, bytes)`` for regular files, never links."""
    stack: list[tuple[Path, str]] = [(root, "")]
    while stack:
        directory, prefix = stack.pop()
        try:
            entries = list(os.scandir(directory))
        except OSError:
            continue
        for entry in entries:
            if _entry_is_link(entry):
                continue
            relative = f"{prefix}{entry.name}"
            try:
                if entry.is_dir(follow_symlinks=False):
                    stack.append((Path(entry.path), f"{relative}/"))
                elif entry.is_file(follow_symlinks=False):
                    yield relative, entry.stat(follow_symlinks=False).st_size
            except OSError:
                continue


def scan_storage(project_path: Path, source_files: Iterable[str | None]) -> tuple[list[dict[str, Any]], int]:
    """Return category summaries and the total regular-file usage of a project."""
    categories = {category: {"id": category, "bytes": 0, "files": 0} for category in CATEGORY_IDS}
    total = 0
    sources = {_relative(value) for value in source_files if value}
    if not project_path.is_dir() or _is_link(project_path):
        return [categories[category] for category in CATEGORY_IDS], total
    for relative, size in _walk_project(project_path):
        category = categories[_category_for(relative, sources)]
        category["bytes"] += size
        category["files"] += 1
        total += size
    return [categories[category] for category in CATEGORY_IDS], total


def scan_outputs(project_path: Path, referenced: set[str], *,
                 min_age_seconds: int = MIN_AGE_SECONDS, now: float | None = None
                 ) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Return (eligible, protected) output folders for the project.

    ``referenced`` must include every token used by stored jobs. Recent folders
    are protected so an in-flight publishing job is never removed.
    """
    root = project_path / "outputs"
    current = time.time() if now is None else now
    eligible: list[dict[str, Any]] = []
    protected: list[dict[str, Any]] = []
    if not root.is_dir() or _is_link(root):
        return eligible, protected
    try:
        entries = sorted(root.iterdir(), key=lambda entry: entry.name)
    except OSError:
        return eligible, protected
    for entry in entries:
        if not TOKEN_RE.fullmatch(entry.name):
            continue
        if _is_link(entry):
            protected.append({"token": entry.name, "bytes": 0, "files": 0, "age_seconds": 0,
                              "reason": "symlink"})
            continue
        if not entry.is_dir():
            continue
        size, files, unsafe = _measure(entry)
        try:
            age = max(0.0, current - entry.stat().st_mtime)
        except OSError:
            age = 0.0
        item = {"token": entry.name, "bytes": size, "files": files, "age_seconds": int(age)}
        if unsafe:
            protected.append({**item, "reason": unsafe})
        elif entry.name in referenced:
            protected.append({**item, "reason": "referenced"})
        elif age < min_age_seconds:
            protected.append({**item, "reason": "recent"})
        else:
            eligible.append(item)
    return eligible, protected


def scan_renders(project_path: Path, referenced: set[str], *,
                 min_age_seconds: int = MIN_AGE_SECONDS, now: float | None = None
                 ) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Return (eligible, protected) old main render files directly under ``outputs``.

    ``referenced`` must contain ``outputs/<name>`` paths used by project state or
    consumer job results. Recent files are protected so an in-flight render is
    never removed.
    """
    root = project_path / "outputs"
    current = time.time() if now is None else now
    eligible: list[dict[str, Any]] = []
    protected: list[dict[str, Any]] = []
    if not root.is_dir() or _is_link(root):
        return eligible, protected
    try:
        entries = sorted(root.iterdir(), key=lambda entry: entry.name)
    except OSError:
        return eligible, protected
    for entry in entries:
        if not RENDER_NAME_RE.fullmatch(entry.name):
            continue
        relative = f"outputs/{entry.name}"
        if _entry_is_link(entry):
            protected.append({"file": entry.name, "bytes": 0, "age_seconds": 0, "reason": "symlink"})
            continue
        try:
            if entry.is_dir():
                continue
            if not entry.is_file():
                protected.append({"file": entry.name, "bytes": 0, "age_seconds": 0, "reason": "special"})
                continue
            info = entry.stat()
        except OSError:
            protected.append({"file": entry.name, "bytes": 0, "age_seconds": 0, "reason": "unreadable"})
            continue
        age = max(0.0, current - info.st_mtime)
        item = {"file": entry.name, "bytes": info.st_size, "age_seconds": int(age)}
        if relative in referenced:
            protected.append({**item, "reason": "referenced"})
        elif age < min_age_seconds:
            protected.append({**item, "reason": "recent"})
        else:
            eligible.append(item)
    return eligible, protected


# ------------------------------------------------------------------- çöp kutusu ----

def _trash_root(project_path: Path) -> Path:
    return project_path / TRASH_DIR


def _iso_time(now: float | None = None) -> str:
    moment = datetime.now(timezone.utc) if now is None else datetime.fromtimestamp(now, timezone.utc)
    return moment.isoformat()


def _manifest_original(manifest: dict[str, Any]) -> str | None:
    """Derive the only paths a manifest is allowed to name."""
    kind, name = manifest.get("kind"), manifest.get("name")
    if not isinstance(name, str):
        return None
    if kind == "staging" and TOKEN_RE.fullmatch(name):
        return f"outputs/{name}"
    if kind == "render" and RENDER_NAME_RE.fullmatch(name):
        return f"outputs/{name}"
    return None


def _valid_manifest(entry_id: str, manifest: Any) -> dict[str, Any] | None:
    if not isinstance(manifest, dict) or manifest.get("id") != entry_id:
        return None
    if manifest.get("status") not in ("pending", "ready"):
        return None
    if _manifest_original(manifest) is None:
        return None
    for key in ("bytes", "files"):
        value = manifest.get(key)
        if not isinstance(value, int) or isinstance(value, bool) or value < 0:
            return None
    if not isinstance(manifest.get("deleted_at"), str):
        return None
    return manifest


def _read_manifest(entry_dir: Path) -> dict[str, Any] | None:
    path = entry_dir / "manifest.json"
    if not path.is_file() or _is_link(path):
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def _write_manifest(entry_dir: Path, manifest: dict[str, Any]) -> None:
    target = entry_dir / "manifest.json"
    temporary = entry_dir / "manifest.json.tmp"
    temporary.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    os.replace(temporary, target)


def _deleted_at(manifest: dict[str, Any], entry_dir: Path) -> float:
    raw = manifest.get("deleted_at")
    try:
        parsed = datetime.fromisoformat(str(raw).replace("Z", "+00:00"))
        if parsed.tzinfo is None:
            parsed = parsed.replace(tzinfo=timezone.utc)
        return parsed.timestamp()
    except (TypeError, ValueError):
        try:
            return entry_dir.stat().st_mtime
        except OSError:
            return 0.0


def _trash_entry(project_path: Path, entry_dir: Path, *, now: float,
                 retention: int = TRASH_RETENTION_SECONDS) -> dict[str, Any] | None:
    """Validate one trash entry and recover a completed pending move if needed."""
    entry_id = entry_dir.name
    if not TOKEN_RE.fullmatch(entry_id) or not entry_dir.is_dir() or _is_link(entry_dir):
        return None
    manifest = _read_manifest(entry_dir)
    manifest = _valid_manifest(entry_id, manifest)
    if manifest is None:
        return None
    name = manifest["name"]
    original = _manifest_original(manifest)
    if original is None:
        return None
    payload_dir = entry_dir / "payload"
    payload = payload_dir / name
    original_path = project_path / original
    if _is_link(payload_dir) or _is_link(payload):
        return None
    if manifest["status"] != "ready":
        payload_exists = payload.exists()
        original_exists = original_path.exists() or _is_link(original_path)
        if payload_exists and not original_exists:
            manifest["status"] = "ready"
            try:
                _write_manifest(entry_dir, manifest)
            except OSError:
                return None
        elif original_exists and not payload_exists:
            shutil.rmtree(entry_dir, ignore_errors=True)
            return None
        elif not original_exists and not payload_exists:
            shutil.rmtree(entry_dir, ignore_errors=True)
            return None
        else:
            return None
    if not payload.exists():
        # A completed restore may have left only the metadata directory behind.
        if original_path.exists() or _is_link(original_path):
            shutil.rmtree(entry_dir, ignore_errors=True)
        return None
    size = files = 0
    for _, file_size in _walk_project(payload_dir):
        size += file_size
        files += 1
    deleted = _deleted_at(manifest, entry_dir)
    age = max(0.0, now - deleted)
    return {
        "id": entry_id, "kind": manifest["kind"], "name": name,
        "bytes": size, "files": files, "deleted_at": manifest["deleted_at"],
        "age_seconds": int(age),
        "expires_in_seconds": max(0, int(retention - age)),
    }


def _trash_entries(project_path: Path, *, now: float,
                   retention: int = TRASH_RETENTION_SECONDS) -> list[dict[str, Any]]:
    root = _trash_root(project_path)
    if not root.is_dir() or _is_link(root):
        return []
    try:
        entries = sorted(root.iterdir(), key=lambda entry: entry.name)
    except OSError:
        return []
    found = [_trash_entry(project_path, entry, now=now, retention=retention) for entry in entries]
    result = [entry for entry in found if entry is not None]
    result.sort(key=lambda entry: entry["age_seconds"])
    return result


def scan_trash(project_path: Path, *, now: float | None = None,
               retention: int = TRASH_RETENTION_SECONDS) -> dict[str, Any]:
    """Return the current trash inventory without purging anything."""
    current = time.time() if now is None else now
    entries = _trash_entries(project_path, now=current, retention=retention)
    return {
        "entries": entries,
        "bytes": sum(entry["bytes"] for entry in entries),
        "files": sum(entry["files"] for entry in entries),
        "retention_seconds": retention,
    }


def _move_to_trash(project_path: Path, source: Path, *, kind: str, name: str, size: int, files: int,
                   batch_id: str, now: float | None) -> dict[str, Any]:
    """Move one file/folder into the project trash, preserving its original name."""
    root = _trash_root(project_path)
    if root.exists() and _is_link(root):
        raise OSError("Çöp kutusu bağlantısı kullanılamaz.")
    root.mkdir(parents=True, exist_ok=True)
    entry_id = uuid.uuid4().hex
    while (root / entry_id).exists():
        entry_id = uuid.uuid4().hex
    entry_dir = root / entry_id
    payload_dir = entry_dir / "payload"
    payload_dir.mkdir(parents=True)
    manifest = {
        "id": entry_id, "kind": kind, "name": name, "bytes": size, "files": files,
        "deleted_at": _iso_time(now), "batch_id": batch_id, "status": "pending",
    }
    moved = False
    try:
        _write_manifest(entry_dir, manifest)
        shutil.move(str(source), str(payload_dir / name))
        moved = True
        manifest["status"] = "ready"
        _write_manifest(entry_dir, manifest)
    except Exception:
        if moved:
            try:
                shutil.move(str(payload_dir / name), str(source))
            except OSError:
                # The data is safe in a recoverable pending entry; leave it there.
                raise
            else:
                shutil.rmtree(entry_dir, ignore_errors=True)
        else:
            shutil.rmtree(entry_dir, ignore_errors=True)
        raise
    return {
        "id": entry_id, "kind": kind, "name": name, "bytes": size, "files": files,
        "deleted_at": manifest["deleted_at"], "age_seconds": 0,
        "expires_in_seconds": TRASH_RETENTION_SECONDS,
    }


def trash_outputs(project_path: Path, referenced: set[str], requested: Iterable[str], *,
                  min_age_seconds: int = MIN_AGE_SECONDS, now: float | None = None) -> dict[str, Any]:
    """Move requested eligible output folders into trash, reporting every outcome."""
    current = time.time() if now is None else now
    eligible, protected = scan_outputs(project_path, referenced, min_age_seconds=min_age_seconds, now=current)
    allowed = {item["token"]: item for item in eligible}
    batch_id = uuid.uuid4().hex
    trashed: list[dict[str, Any]] = []
    failed: list[str] = []
    skipped: list[str] = []
    for token in dict.fromkeys(requested):
        item = allowed.get(token)
        if item is None:
            skipped.append(token)
            continue
        try:
            trashed.append(_move_to_trash(
                project_path, project_path / "outputs" / token, kind="staging", name=token,
                size=item["bytes"], files=item["files"], batch_id=batch_id, now=current))
        except OSError:
            failed.append(token)
    remaining = [item for item in eligible if item["token"] not in {entry["name"] for entry in trashed}]
    return {
        "trashed": trashed,
        "moved_bytes": sum(entry["bytes"] for entry in trashed),
        "failed": failed,
        "skipped": skipped,
        "eligible": remaining,
        "protected": protected,
    }


def trash_renders(project_path: Path, referenced: set[str], requested: Iterable[str], *,
                  min_age_seconds: int = MIN_AGE_SECONDS, now: float | None = None) -> dict[str, Any]:
    """Move requested old main renders into trash, reporting every outcome."""
    current = time.time() if now is None else now
    eligible, protected = scan_renders(project_path, referenced, min_age_seconds=min_age_seconds, now=current)
    allowed = {item["file"]: item for item in eligible}
    batch_id = uuid.uuid4().hex
    trashed: list[dict[str, Any]] = []
    failed: list[str] = []
    skipped: list[str] = []
    for name in dict.fromkeys(requested):
        item = allowed.get(name)
        if item is None:
            skipped.append(name)
            continue
        try:
            trashed.append(_move_to_trash(
                project_path, project_path / "outputs" / name, kind="render", name=name,
                size=item["bytes"], files=1, batch_id=batch_id, now=current))
        except OSError:
            failed.append(name)
    remaining = [item for item in eligible if item["file"] not in {entry["name"] for entry in trashed}]
    return {
        "trashed": trashed,
        "moved_bytes": sum(entry["bytes"] for entry in trashed),
        "failed": failed,
        "skipped": skipped,
        "eligible": remaining,
        "protected": protected,
    }


def purge_expired_trash(project_path: Path, *, now: float | None = None,
                        retention: int = TRASH_RETENTION_SECONDS) -> dict[str, Any]:
    """Permanently remove trash entries whose seven-day window has elapsed."""
    current = time.time() if now is None else now
    entries = _trash_entries(project_path, now=current, retention=retention)
    root = _trash_root(project_path)
    purged: list[dict[str, Any]] = []
    failed: list[str] = []
    for entry in entries:
        if entry["age_seconds"] < retention:
            continue
        try:
            shutil.rmtree(root / entry["id"])
        except OSError:
            failed.append(entry["id"])
            continue
        purged.append(entry)
    return {"purged": purged, "freed_bytes": sum(entry["bytes"] for entry in purged), "failed": failed}


def purge_all_expired_trash(projects_root: Path, *, now: float | None = None,
                            retention: int = TRASH_RETENTION_SECONDS) -> None:
    """Best-effort startup sweep; one unreadable project never stops the rest."""
    current = time.time() if now is None else now
    if not projects_root.is_dir() or _is_link(projects_root):
        return
    try:
        projects = list(projects_root.iterdir())
    except OSError:
        return
    for project in projects:
        if not project.is_dir() or _is_link(project):
            continue
        try:
            purge_expired_trash(project, now=current, retention=retention)
        except OSError:
            continue


def restore_trash(project_path: Path, ids: Iterable[str], *, now: float | None = None,
                  retention: int = TRASH_RETENTION_SECONDS) -> dict[str, Any]:
    """Restore entries to ``outputs`` only when the original path is still free."""
    current = time.time() if now is None else now
    purge_expired_trash(project_path, now=current, retention=retention)
    root = _trash_root(project_path)
    outputs = project_path / "outputs"
    restored: list[dict[str, Any]] = []
    skipped: list[str] = []
    failed: list[str] = []
    for entry_id in dict.fromkeys(ids):
        if not TOKEN_RE.fullmatch(entry_id):
            skipped.append(entry_id)
            continue
        entry = _trash_entry(project_path, root / entry_id, now=current, retention=retention)
        if entry is None or entry["age_seconds"] >= retention:
            skipped.append(entry_id)
            continue
        if not outputs.is_dir() or _is_link(outputs):
            try:
                outputs.mkdir(parents=True, exist_ok=True)
            except OSError:
                failed.append(entry_id)
                continue
        target = outputs / entry["name"]
        if target.exists() or _is_link(target):
            skipped.append(entry_id)
            continue
        try:
            shutil.move(str(root / entry_id / "payload" / entry["name"]), str(target))
            shutil.rmtree(root / entry_id, ignore_errors=True)
        except OSError:
            failed.append(entry_id)
            continue
        restored.append(entry)
    return {"restored": restored, "skipped": skipped, "failed": failed}


def empty_trash(project_path: Path, ids: Iterable[str] | None = None, *, now: float | None = None,
                retention: int = TRASH_RETENTION_SECONDS) -> dict[str, Any]:
    """Permanently delete selected trash entries; an empty list means everything."""
    current = time.time() if now is None else now
    root = _trash_root(project_path)
    available = _trash_entries(project_path, now=current, retention=retention)
    requested = list(ids) if ids is not None else []
    if requested:
        by_id = {entry["id"]: entry for entry in available}
        selected = [by_id[entry_id] for entry_id in dict.fromkeys(requested) if entry_id in by_id]
        skipped = [entry_id for entry_id in dict.fromkeys(requested) if entry_id not in by_id]
    else:
        selected = available
        skipped = []
    purged: list[dict[str, Any]] = []
    failed: list[str] = []
    for entry in selected:
        try:
            shutil.rmtree(root / entry["id"])
        except OSError:
            failed.append(entry["id"])
            continue
        purged.append(entry)
    return {
        "purged": purged,
        "freed_bytes": sum(entry["bytes"] for entry in purged),
        "failed": failed,
        "skipped": skipped,
    }
